// Snapshots: pull the deployed state once, write it as a folder (the protocol layout)
// or as a JS module for `embeddedSnapshot` on edge runtimes.
import { Client, type ClientOptions, type EmbeddedSnapshot } from './client.js';
import { atomicWrite, encodeUtf8, joinPath, loadFs, readFile } from './io.js';
import { VERSION } from './version.js';

export type PullOptions = Omit<
  ClientOptions,
  'cacheDir' | 'snapshotDir' | 'embeddedSnapshot' | 'autoRefresh' | 'startEmpty' | 'onUpdate' | 'apiKey'
>;

export interface PullResult {
  snapshot: EmbeddedSnapshot;
  workspace: string;
  revision: number;
  promptCount: number;
  source: string;
}

/** Fetch and verify the deployed manifest and its blobs from the network mirrors. */
export async function pullSnapshot(options: PullOptions): Promise<PullResult> {
  const client = await Client.create({
    logLevel: 'error',
    ...options,
    autoRefresh: false,
    startEmpty: false,
  } as ClientOptions);
  try {
    const st = client.status();
    return {
      snapshot: client.toSnapshot()!,
      workspace: st.workspace,
      revision: st.revision,
      promptCount: st.promptCount,
      source: st.source,
    };
  } finally {
    await client.close();
  }
}

const sameBytes = (a: Uint8Array, b: Uint8Array) => a.length === b.length && a.every((x, i) => x === b[i]);

/** Write a snapshot as a folder in the protocol layout (Node, Bun, Deno). Returns the number of files written. */
export async function writeSnapshotFolder(snapshot: EmbeddedSnapshot, dir: string): Promise<number> {
  const fs = await loadFs();
  if (!fs) throw new Error('writeSnapshotFolder needs a file system (Node, Bun or Deno)');
  let written = 0;
  // Blobs first, then the manifest, so a reader never sees a manifest without its blobs.
  const paths = Object.keys(snapshot.files).sort((a, b) => Number(a.startsWith('envs/')) - Number(b.startsWith('envs/')));
  for (const rel of paths) {
    const path = joinPath(dir, rel);
    const data = encodeUtf8(snapshot.files[rel]!);
    const existing = await readFile(fs, path);
    if (existing.kind === 'ok' && sameBytes(existing.body!, data)) continue;
    await atomicWrite(fs, path, data);
    written++;
  }
  return written;
}

/** Source of an importable module exporting the snapshot. `format`: `esm` (default), `cjs` or `ts`. */
export function snapshotModuleSource(snapshot: EmbeddedSnapshot, format: 'esm' | 'cjs' | 'ts' = 'esm'): string {
  const head = `// Generated by @keepyourprompts/sdk ${VERSION} snapshot. Do not edit: re-run the snapshot command.\n`;
  const body = JSON.stringify({ kyp: 1, files: snapshot.files }, null, 2);
  if (format === 'cjs') return `${head}'use strict';\nmodule.exports = Object.freeze(${body});\n`;
  if (format === 'ts')
    return `${head}import type { EmbeddedSnapshot } from '@keepyourprompts/sdk';\n\nconst snapshot: EmbeddedSnapshot = ${body};\nexport default snapshot;\n`;
  return `${head}export default Object.freeze(${body});\n`;
}

/** Declarations for an ESM/CJS snapshot module. */
export function snapshotModuleTypes(): string {
  return "declare const snapshot: import('@keepyourprompts/sdk').EmbeddedSnapshot;\nexport default snapshot;\n";
}
